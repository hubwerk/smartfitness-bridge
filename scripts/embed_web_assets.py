"""Embed the web UI into the firmware as a gzipped byte array.

Runs automatically as a PlatformIO pre-build script (see platformio.ini) and
can also be run by hand: ``python3 scripts/embed_web_assets.py``.
Output: include/generated/web_assets.h (generated, not committed). The gzip
stream is deterministic (no timestamp/file name) so builds are reproducible.
"""

import gzip
import io
import os

try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SOURCE = os.path.join(ROOT, "web", "index.html")
TARGET = os.path.join(ROOT, "include", "generated", "web_assets.h")


def compress(data: bytes) -> bytes:
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return buffer.getvalue()


def render(payload: bytes) -> str:
    lines = []
    for offset in range(0, len(payload), 16):
        chunk = payload[offset:offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return (
        "// Generated by scripts/embed_web_assets.py from web/index.html - do not edit.\n"
        "#pragma once\n"
        "#include <cstdint>\n\n"
        f"// gzip, {len(payload)} bytes\n"
        "static const std::uint8_t kIndexHtmlGz[] = {\n" + "\n".join(lines) + "\n};\n"
    )


def main() -> None:
    with open(SOURCE, "rb") as handle:
        content = render(compress(handle.read()))
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    if os.path.exists(TARGET):
        with open(TARGET, "r", encoding="utf-8") as handle:
            if handle.read() == content:
                return
    with open(TARGET, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(f"embed_web_assets: wrote {os.path.relpath(TARGET, ROOT)}")


main()
